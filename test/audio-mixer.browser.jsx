const tick = (ms = 100) => new Promise((r) => setTimeout(r, ms));
const assert = (ok, message) => { if (!ok) throw new Error(message); };
const root = () => document.getElementById('root');
const input = (el, value) => { el.value = value; el.dispatchEvent(new Event('input', { bubbles: true })); };

export async function verifyAudio() {
  const ctx = new AudioContext({ sampleRate: 48000 });
  await ctx.resume();
  const tone = ctx.createOscillator();
  const amplitude = ctx.createGain();
  amplitude.gain.value = 0.1;
  const raw = ctx.createMediaStreamDestination();
  tone.connect(amplitude).connect(raw);
  tone.start();
  const mixer = createMicMixer(ctx, raw.stream, FLAT_MIX);
  await tick(300);
  const flat = mixer.read(performance.now());
  assert(Math.abs(flat.rms - (-23.01)) < 0.3, `Flat should retain the source amplitude: ${flat.rms}`);
  mixer.set({ ...FLAT_MIX, gain: 6 });
  await tick(300);
  const boosted = mixer.read(performance.now());
  assert(Math.abs(boosted.rms - flat.rms - 6) < 0.3, `Gain should boost real audio by 6 dB: ${boosted.rms - flat.rms}`);
  assert(Math.abs(boosted.input - flat.input) < 0.3, 'Input meter should stay before gain');
  // Decode the actual processed MediaRecorder output, as used by capture and Test.
  const recorder = new MediaRecorder(mixer.stream, { mimeType: 'audio/webm;codecs=opus' });
  const chunks = [];
  recorder.ondataavailable = (e) => chunks.push(e.data);
  const stopped = new Promise((resolve) => { recorder.onstop = resolve; });
  recorder.start();
  await tick(500);
  recorder.stop();
  await stopped;
  const audio = await ctx.decodeAudioData(await new Blob(chunks).arrayBuffer());
  const samples = audio.getChannelData(0).slice(5000, 15000);
  const recorded = 20 * Math.log10(Math.sqrt(samples.reduce((sum, n) => sum + n * n, 0) / samples.length));
  assert(Math.abs(recorded - boosted.rms) < 0.7, `Recorded stream must include gain: ${recorded}, meter: ${boosted.rms}`);
  mixer.set({ ...FLAT_MIX, gain: 24, compressor: true, threshold: -24, ratio: 8 });
  await tick(400);
  const compressed = mixer.read(performance.now());
  assert(compressed.reduction < -10, 'Compressor should reduce a loud signal');
  assert(compressed.output < flat.output + 24 - 6, `Compressor must affect the output, not just the display: ${JSON.stringify(compressed)}`);
  mixer.dispose();
  tone.stop();
  raw.stream.getTracks().forEach((t) => t.stop());
  await ctx.close();
  return { status: 'passed', flatDb: flat.rms, boostedDb: boosted.rms, recordedDb: recorded, reductionDb: compressed.reduction };
}

export async function verifyMixerUI() {
  engine.mics.value = [{ id: 'test-mic', label: 'Studio microphone' }];
  saveSettings({ micId: 'test-mic', micMixer: FLAT_MIX });
  render(<Recorder active={true} />, root());
  await tick();
  assert(document.querySelector('[aria-label="Input gain"]').value === '0', 'Recorder gain starts at zero');
  input(document.querySelector('[aria-label="Input gain"]'), 6);
  await tick();
  assert(settings.value.micMixer.gain === 6, 'Inline gain updates saved settings');
  document.querySelector('.mic-open-mixer').click();
  await tick();
  assert(document.querySelector('.mic-mixer'), 'Mixer opens in a separate dialog');
  assert(document.querySelector('.mic-mixer [aria-label="Input gain"]').value === '6', 'Mixer shares the inline gain');
  const select = document.querySelector('[aria-label="Microphone preset"]');
  select.value = 'warm';
  select.dispatchEvent(new Event('change', { bubbles: true }));
  await tick();
  assert(settings.value.micMixer.low === 3 && settings.value.micMixer.compressor, 'Preset changes actual processing settings');
  input(document.querySelector('[aria-label="High · 5 kHz"]'), 5);
  await tick();
  assert(document.querySelector('[aria-label="Microphone preset"]').value === 'custom', 'Manual change selects Custom');
  [...document.querySelectorAll('.mic-mixer button')].find((b) => b.textContent === 'Done').click();
  await tick();
  assert(!document.querySelector('.mic-mixer'), 'Done closes mixer');
  assert(JSON.parse(localStorage.getItem('settings')).micMixer.high === 5, 'Closing preserves mixer settings');
  document.querySelector('.mic-open-mixer').click();
  await tick();
  assert(document.querySelector('[aria-label="High · 5 kHz"]').value === '5', 'Reopen restores values');
  [...document.querySelectorAll('.mic-mixer button')].find((b) => b.textContent.includes('Reset to Flat')).click();
  await tick();
  assert(JSON.stringify(settings.value.micMixer) === JSON.stringify(FLAT_MIX), 'Reset restores all defaults');
  assert(document.querySelector('[aria-label="Microphone preset"]').value === 'flat', 'Reset selects Flat');
  assert(document.querySelector('.mic-mixer').getBoundingClientRect().right <= window.innerWidth, 'Mixer fits the window');
  engine.micLevels.value = { input: -15, output: -9, rms: -20, held: -6, reduction: -3.2, spectrum: Array.from({length:24}, (_, i) => 10 + Math.sin(i/3)**2 * 75) };
  await tick();
  return { status: 'passed', checks: 12 };
}

